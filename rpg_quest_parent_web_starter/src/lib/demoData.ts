function daily(
  date: string,
  assigned: number,
  claimed: number,
  completionRate: number,
  avgSubmitHours: number,
  categoryPairs: Record<string, [number, number]>,
  rejected = 0
): DailyAnalytics {
  return {
    id: date,
    date,
    familyId: DEMO_FAMILY_ID,
    childId: DEMO_CHILD_ID,
    assignedCount: assigned,
    viewedCount: assigned,
    submittedCount: Math.max(claimed + rejected, claimed),
    approvedCount: claimed,
    rejectedCount: rejected,
    claimedCount: claimed,
    cancelledCount: 0,
    reminderCount: rejected,
    completionRate,
    approvalRate: claimed + rejected > 0 ? claimed / (claimed + rejected) : 0,
    rejectionRate: claimed + rejected > 0 ? rejected / (claimed + rejected) : 0,
    claimRate: claimed > 0 ? 1 : 0,
    avgSubmitHours,
    avgClaimHours: avgSubmitHours + 3,
    activeQuestCount: Math.max(0, assigned - claimed),
    categoryStats: Object.fromEntries(
      Object.entries(categoryPairs).map(([category, [categoryAssigned, categoryClaimed]]) => [
        category,
        {
          assigned: categoryAssigned,
          viewed: categoryAssigned,
          submitted: categoryAssigned,
          approved: categoryClaimed,
          rejected: Math.max(0, categoryAssigned - categoryClaimed),
          claimed: categoryClaimed,
          avgSubmitHours,
          completionRate: categoryAssigned > 0 ? categoryClaimed / categoryAssigned : 0,
          rejectionRate: categoryAssigned > 0 ? Math.max(0, categoryAssigned - categoryClaimed) / categoryAssigned : 0,
        },
      ])
    ),
    updatedAt: null,
  };
}
